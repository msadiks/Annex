#!/usr/bin/env bash
# Regenerates crates/annex-win/src/ffmpeg/sys.rs from the headers installed by
# build-mingw.sh. Run after bumping FFMPEG_TAG. Needs bindgen-cli and libclang.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
FF="${1:-$ROOT/third_party/ffmpeg-build}"
OUT="$ROOT/crates/annex-win/src/ffmpeg/sys.rs"
SYSROOT="${MINGW_SYSROOT:-/usr/x86_64-w64-mingw32}"
HDR="$(mktemp --suffix=.h)"
cat > "$HDR" <<'H'
#include <libavcodec/avcodec.h>
#include <libavutil/hwcontext.h>
#include <libavutil/pixdesc.h>
#include <libavutil/log.h>
H
{
  echo "// Generated by tools/ffmpeg/gen-bindings.sh from FFmpeg $(cat "$FF/include/libavutil/ffversion.h" | grep -o '"n[^"]*"' || echo '?'). Do not edit."
  bindgen "$HDR" \
    --allowlist-function 'avcodec_(find_decoder|alloc_context3|free_context|open2|send_packet|receive_frame|get_hw_frames_parameters|flush_buffers)' \
    --allowlist-function 'av_(packet_alloc|packet_free|frame_alloc|frame_free|frame_unref|frame_move_ref|buffer_ref|buffer_unref|hwdevice_ctx_alloc|hwdevice_ctx_init|hwframe_ctx_init|log_set_level|log_set_callback|get_pix_fmt_name|strerror|version_info)' \
    --allowlist-type 'AVClass|AVCodecContext|AVFrame|AVPacket|AVHWDeviceContext|AVHWFramesContext|AVBufferRef|AVCodec|AVPixelFormat|AVCodecID|AVHWDeviceType' \
    --allowlist-var 'AV_CODEC_FLAG_LOW_DELAY|AV_CODEC_FLAG2_FAST|AV_LOG_.*|AVERROR_EOF' \
    --no-layout-tests --no-doc-comments --use-core \
    --rustified-enum 'AVPixelFormat|AVCodecID|AVHWDeviceType' \
    --default-enum-style consts \
    --opaque-type 'AVClass|AVCodecInternal|AVCodecHWConfigInternal' \
    -- -I"$FF/include" --target=x86_64-pc-windows-gnu --sysroot="$SYSROOT" -I"$SYSROOT/include"
} > "$OUT"
rm -f "$HDR"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
